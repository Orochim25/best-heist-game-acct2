/** Totals the title screen prints: heists, guards, treasures, gadgets. */
export function ledgerTotals() {
  let guards = 0;
  let treasures = 0;
  for (const level of LEVELS) {
    guards += level.guards.length;
    for (const row of level.map) for (const ch of row) if (ch === 'T') treasures += 1;
  }
  return { heists: LEVELS.length, guards, treasures, gadgets: 4 };
}
